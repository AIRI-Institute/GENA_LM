#!/usr/bin/env python3
"""Prepare exact AlphaGenome track mappings for qnorm benchmarking."""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path

import pandas as pd


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--support-summary", required=True)
    parser.add_argument("--alphagenome-rna-metadata", required=True)
    parser.add_argument("--mapping-csv", required=True)
    parser.add_argument("--mapping-py", required=True)
    parser.add_argument("--excluded-csv", required=True)
    return parser.parse_args()


def write_mapping_py(path: Path, mapping: dict[str, list[str]], excluded: pd.DataFrame) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as handle:
        handle.write("# Generated by prepare_alphagenome_supported_benchmark.py\n")
        handle.write("# Keys are exact AlphaGenome RNA-seq track names; values are qnorm target ids.\n")
        handle.write("TRACK_TO_QNORM_IDS = {\n")
        for track_name in sorted(mapping):
            ids = sorted(mapping[track_name])
            handle.write(f"    {track_name!r}: {ids!r},\n")
        handle.write("}\n\n")
        handle.write("ONTOLOGY_LIST = list(TRACK_TO_QNORM_IDS.keys())\n\n")
        handle.write("EXCLUDED_ONTOLOGY_ONLY = [\n")
        for row in excluded.to_dict("records"):
            handle.write(f"    {row!r},\n")
        handle.write("]\n")


def main() -> int:
    args = parse_args()
    support = pd.read_csv(args.support_summary, dtype=str).fillna("")
    metadata = pd.read_csv(args.alphagenome_rna_metadata, dtype=str).fillna("")

    if "name" not in metadata.columns:
        raise SystemExit("AlphaGenome metadata must contain a 'name' column.")

    alpha_track_names = set(metadata["name"])

    supported = support[support["alphagenome_supported"] == "yes"].copy()
    supported["track_name"] = supported["ontology_curie"] + " " + supported["assay"]
    supported["exact_track_supported"] = supported["track_name"].isin(alpha_track_names)

    exact = supported[supported["exact_track_supported"]].copy()
    excluded = supported[~supported["exact_track_supported"]].copy()

    mapping: dict[str, list[str]] = defaultdict(list)
    for row in exact.to_dict("records"):
        mapping[row["track_name"]].append(row["id"])

    mapping_rows = []
    for track_name, qnorm_ids in sorted(mapping.items()):
        meta = metadata[metadata["name"] == track_name].head(1)
        meta_row = meta.iloc[0].to_dict() if len(meta) else {}
        for qnorm_id in sorted(qnorm_ids):
            source_row = exact[(exact["track_name"] == track_name) & (exact["id"] == qnorm_id)].iloc[0]
            mapping_rows.append(
                {
                    "track_name": track_name,
                    "qnorm_id": qnorm_id,
                    "original_id": source_row["original_id"],
                    "targets_identifier_base": source_row["targets_identifier_base"],
                    "ontology_curie": source_row["ontology_curie"],
                    "biosample_name": source_row["biosample_name"],
                    "assay": source_row["assay"],
                    "alphagenome_data_source": meta_row.get("data_source", ""),
                    "alphagenome_strand_entries": str((metadata["name"] == track_name).sum()),
                }
            )

    mapping_out = Path(args.mapping_csv)
    mapping_out.parent.mkdir(parents=True, exist_ok=True)
    with mapping_out.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(mapping_rows[0]))
        writer.writeheader()
        writer.writerows(mapping_rows)

    excluded_cols = [
        "id",
        "original_id",
        "targets_identifier_base",
        "ontology_curie",
        "biosample_name",
        "assay",
        "track_name",
    ]
    excluded_out = Path(args.excluded_csv)
    excluded_out.parent.mkdir(parents=True, exist_ok=True)
    excluded[excluded_cols].to_csv(excluded_out, index=False)

    write_mapping_py(Path(args.mapping_py), dict(mapping), excluded[excluded_cols])

    print(f"Exact AlphaGenome track rows: {len(mapping_rows)}")
    print(f"Exact AlphaGenome unique tracks: {len(mapping)}")
    print(f"Ontology-supported but exact assay track missing: {len(excluded)}")
    print(f"Wrote {args.mapping_csv}")
    print(f"Wrote {args.mapping_py}")
    print(f"Wrote {args.excluded_csv}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
