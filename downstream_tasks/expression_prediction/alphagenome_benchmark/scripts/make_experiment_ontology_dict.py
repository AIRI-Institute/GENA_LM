#!/usr/bin/env python3
"""Create EXPERIMENT_ONTOLOGY_DICT and AlphaGenome support summaries."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

import pandas as pd


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--ontology-map", required=True, help="CSV from build_alphagenome_ontology_map.py.")
    parser.add_argument("--alphagenome-rna-metadata", help="CSV from dump_alphagenome_rna_metadata.py.")
    parser.add_argument("--dict-py", required=True, help="Python file to write.")
    parser.add_argument("--summary-csv", required=True, help="Merged support summary CSV.")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    ontology = pd.read_csv(args.ontology_map, dtype=str).fillna("")

    supported_terms: set[str] | None = None
    if args.alphagenome_rna_metadata:
        metadata = pd.read_csv(args.alphagenome_rna_metadata, dtype=str).fillna("")
        if "ontology_curie" not in metadata.columns:
            raise SystemExit("AlphaGenome RNA metadata must contain an ontology_curie column.")
        supported_terms = set(metadata["ontology_curie"])
        track_counts = metadata.groupby("ontology_curie").size().rename("alphagenome_rna_track_count")
        ontology = ontology.merge(track_counts, how="left", left_on="ontology_curie", right_index=True)
        ontology["alphagenome_rna_track_count"] = (
            ontology["alphagenome_rna_track_count"].fillna(0).astype(int).astype(str)
        )
        ontology["alphagenome_supported"] = ontology["ontology_curie"].isin(supported_terms).map(
            {True: "yes", False: "no"}
        )
    else:
        ontology["alphagenome_rna_track_count"] = ""
        ontology["alphagenome_supported"] = "unknown"

    ontology.to_csv(args.summary_csv, index=False)

    dict_rows = ontology[ontology["ontology_curie"] != ""]
    if supported_terms is not None:
        dict_rows = dict_rows[dict_rows["ontology_curie"].isin(supported_terms)]

    pairs = dict(zip(dict_rows["id"], dict_rows["ontology_curie"]))
    out = Path(args.dict_py)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w") as handle:
        handle.write("# Generated by make_experiment_ontology_dict.py\n")
        handle.write("EXPERIMENT_ONTOLOGY_DICT = {\n")
        for experiment_id, ontology_curie in sorted(pairs.items()):
            handle.write(f"    {experiment_id!r}: {ontology_curie!r},\n")
        handle.write("}\n")

    print(f"Wrote {out} with {len(pairs)} experiment-to-ontology mappings.")
    print(f"Wrote {args.summary_csv} with {len(ontology)} rows.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
